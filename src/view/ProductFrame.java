    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:

        int selectedRow = tblProducts.getSelectedRow();

        if (selectedRow == -1) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please select a product from the table.",
                    "Validation Error",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        try {

            int productId =
                    Integer.parseInt(
                            tblProducts.getValueAt(
                                    selectedRow, 0
                            ).toString()
                    );

            String productName =
                    txtProductName.getText().trim();

            if (productName.isEmpty()) {

                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Please enter product name.",
                        "Validation Error",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                );

                return;
            }

            double sellingPrice =
                    Double.parseDouble(
                            txtSellingPrice.getText().trim()
                    );

            double reorderLevel =
                    Double.parseDouble(
                            txtRecorderLevel.getText().trim()
                    );

            String categoryName =
                    cmbCategory.getSelectedItem().toString();

            dao.ProductDAO productDAO =
                    new dao.ProductDAO();

            int categoryId =
                    productDAO.getCategoryIdByName(
                            categoryName
                    );

            if (categoryId == 0) {

                throw new Exception(
                        "Selected category was not found."
                );
            }

            model.Product product =
                    new model.Product();

            product.setProductId(productId);
            product.setProductName(productName);
            product.setCategoryId(categoryId);
            product.setUnit(
                    cmbUnit.getSelectedItem().toString()
            );
            product.setSellingPrice(sellingPrice);
            product.setReorderLevel(reorderLevel);

            productDAO.updateProduct(product);

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Product updated successfully.",
                    "Success",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            loadProducts();

        } catch (NumberFormatException e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter valid numeric values.",
                    "Validation Error",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

        } catch (Exception e) {

            e.printStackTrace();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Unable to update product:\n"
                    + e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        // TODO add your handling code here:
        int selectedRow = tblProducts.getSelectedRow();

        if (selectedRow == -1) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please select a product from the table.",
                    "Validation Error",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

            return;
        }

        int productId =
                Integer.parseInt(
                        tblProducts.getValueAt(
                                selectedRow, 0
                        ).toString()
                );

        String productName =
                tblProducts.getValueAt(
                        selectedRow, 1
                ).toString();

        int confirm =
                javax.swing.JOptionPane.showConfirmDialog(
                        this,
                        "Are you sure you want to deactivate product:\n"
                        + productName + "?",
                        "Confirm Delete",
                        javax.swing.JOptionPane.YES_NO_OPTION,
                        javax.swing.JOptionPane.QUESTION_MESSAGE
                );

        if (confirm != javax.swing.JOptionPane.YES_OPTION) {
            return;
        }

        try {

            dao.ProductDAO productDAO =
                    new dao.ProductDAO();

            productDAO.deleteProduct(productId);

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Product deleted successfully.",
                    "Success",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            loadProducts();

            txtProductName.setText("");
            txtSellingPrice.setText("");
            txtStockQuantity.setText("");
            txtRecorderLevel.setText("");

            if (cmbCategory.getItemCount() > 0) {
                cmbCategory.setSelectedIndex(0);
            }

            if (cmbUnit.getItemCount() > 0) {
                cmbUnit.setSelectedIndex(0);
            }

        } catch (Exception e) {

            e.printStackTrace();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Unable to delete product:\n"
                    + e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

