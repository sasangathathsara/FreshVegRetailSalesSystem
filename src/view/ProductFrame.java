    private void loadProducts() {

        try {

            dao.ProductDAO productDAO =
                    new dao.ProductDAO();

            java.util.List<model.Product> products =
                    productDAO.getAllProducts();

            javax.swing.table.DefaultTableModel tableModel =
                    (javax.swing.table.DefaultTableModel)
                    tblProducts.getModel();

            tableModel.setRowCount(0);

            for (model.Product product : products) {

                tableModel.addRow(new Object[]{
                    product.getProductId(),
                    product.getProductName(),
                    product.getCategoryName(),
                    product.getUnit(),
                    product.getSellingPrice(),
                    product.getSellingPrice(),
                    product.getStockQuantity()
                });
            }

        } catch (Exception e) {

            e.printStackTrace();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Unable to load products:\n"
                    + e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }
    
    private void loadCategories() {

        try {

            dao.ProductDAO productDAO = new dao.ProductDAO();

            java.util.List<String> categories =
                    productDAO.getActiveCategoryNames();

            cmbCategory.removeAllItems();

            for (String category : categories) {
                cmbCategory.addItem(category);
            }

        } catch (Exception e) {

            e.printStackTrace();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Unable to load categories:\n" + e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }
    
    private void loadUnits() {

        try {

            dao.ProductDAO productDAO = new dao.ProductDAO();

            java.util.List<String> units =
                    productDAO.getExistingUnits();

            cmbUnit.removeAllItems();

            for (String unit : units) {
                cmbUnit.addItem(unit);
            }

        } catch (Exception e) {

            e.printStackTrace();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Unable to load units:\n" + e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }


