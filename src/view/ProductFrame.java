    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:

        try {

            String productName = txtProductName.getText().trim();

            if (productName.isEmpty()) {
                javax.swing.JOptionPane.showMessageDialog(
                        this,
                        "Please enter product name.",
                        "Validation Error",
                        javax.swing.JOptionPane.WARNING_MESSAGE
                );
                return;
            }

            double sellingPrice =
                    Double.parseDouble(txtSellingPrice.getText().trim());

            double reorderLevel =
                    Double.parseDouble(txtRecorderLevel.getText().trim());

            dao.ProductDAO productDAO =
                    new dao.ProductDAO();

            model.Product product =
                    new model.Product();

            product.setProductCode(
                    "P" + System.currentTimeMillis()
            );

            product.setProductName(productName);

            String categoryName =
                    cmbCategory.getSelectedItem().toString();

            int categoryId =
                    productDAO.getCategoryIdByName(categoryName);

            if (categoryId == 0) {
                throw new Exception(
                        "Selected category was not found."
                );
            }

            product.setCategoryId(categoryId);

            product.setUnit(
                    cmbUnit.getSelectedItem().toString()
            );

            product.setSellingPrice(sellingPrice);

            product.setReorderLevel(reorderLevel);

            productDAO.addProduct(product);

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Product added successfully.",
                    "Success",
                    javax.swing.JOptionPane.INFORMATION_MESSAGE
            );

            loadProducts();

        } catch (NumberFormatException e) {

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Please enter valid numeric values for price and reorder level.",
                    "Validation Error",
                    javax.swing.JOptionPane.WARNING_MESSAGE
            );

        } catch (Exception e) {

            e.printStackTrace();

            javax.swing.JOptionPane.showMessageDialog(
                    this,
                    "Unable to add product:\n" + e.getMessage(),
                    "Error",
                    javax.swing.JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnAddActionPerformed

